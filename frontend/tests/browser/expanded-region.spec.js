import {test,expect} from '@playwright/test';
import {mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const output=new URL('../../../evidence/map-expansion/',import.meta.url);
mkdirSync(output,{recursive:true});

test('expanded 7.5 km terrain selection loads verified grid and routes on the matching API region',async({page})=>{
  await page.setViewportSize({width:1600,height:1000});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('combobox',{name:'Terrain coverage'})).toHaveValue('jezero-m1');
  const thermalAsset=page.waitForResponse(response=>response.url().endsWith('/data/expanded/environment-map/manifest.json'));
  await page.getByRole('combobox',{name:'Terrain coverage'}).selectOption('expanded-7p5km');
  await expect(page.getByText(/7\.5 × 7\.5 km native DEM/)).toBeVisible();
  await expect(page.getByText(/Verified terrain connected/)).toBeVisible();
  await expect(page.getByRole('checkbox',{name:'Terrain slope'})).not.toBeChecked();
  await page.getByRole('button',{name:'Load verification pair'}).click();
  await page.getByRole('button',{name:/Compare routes/}).click();
  await expect(page.getByTestId('map-route-status')).toBeVisible({timeout:30000});
  await expect(page.getByTestId('distance-distance')).toBeVisible();
  const geology=page.getByRole('checkbox',{name:'Geological features context',exact:true});
  const geologyAsset=page.waitForResponse(response=>response.url().endsWith('/data/expanded/geology/sim3464-units.geojson'));
  await geology.check();
  expect((await geologyAsset).status()).toBe(200);
  await expect(page.getByText(/VERIFIED GIS \/ 7\.5 KM \/ 19 intersecting polygons/)).toBeVisible();
  const crism=page.getByRole('checkbox',{name:'CRISM D2300 spectral index context',exact:true});
  const crismAsset=page.waitForResponse(response=>response.url().endsWith('/data/expanded/crism/manifest.json'));
  await crism.check();
  expect((await crismAsset).status()).toBe(200);
  await expect(page.getByText(/VERIFIED CRISM \/ 38\.4% valid cells/)).toBeVisible();
  await crism.uncheck();
  await geology.uncheck();
  const thermal=page.getByLabel('Surface thermal response map',{exact:true});
  await expect(thermal).toBeEnabled();
  expect((await thermalAsset).status()).toBe(200);
  await thermal.check();
  expect((await thermalAsset).status()).toBe(200);
  await expect(page.getByText('THERMAL INERTIA · NOT TEMPERATURE',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:/Sample map center/}).click();
  await expect(page.getByTestId('thermal-value')).toBeVisible();
  await page.screenshot({path:fileURLToPath(new URL('expanded-region-desktop.png',output))});
  expect(errors).toEqual([]);
});
